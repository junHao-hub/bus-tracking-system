import { writeFileSync } from "node:fs";
import { STOPS } from "../src/data/stops.js";

// Set LOOP to true if the bus returns to the first stop at the end
const LOOP = true;

const points = LOOP ? [...STOPS, STOPS[0]] : STOPS;
const coordinates = points.map((s) => `${s.longitude},${s.latitude}`).join(";");
const url = `https://router.project-osrm.org/route/v1/driving/${coordinates}?overview=full&geometries=geojson`;

const response = await fetch(url);
const data = await response.json();

if (data.code !== "Ok") {
  console.error("Routing failed", data);
  process.exit(1);
}

// OSRM returns [longitude, latitude] but Leaflet needs [latitude, longitude]
const route = data.routes[0].geometry.coordinates.map(([lng, lat]) => [lat, lng]);

const content =
  "// Generated by scripts/generateRoute.mjs, do not edit by hand\n" +
  "export const ROUTE = " +
  JSON.stringify(route) +
  ";\n";

writeFileSync("src/data/route.js", content);
console.log(`Saved ${route.length} route points`);