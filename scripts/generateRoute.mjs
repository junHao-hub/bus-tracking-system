import { writeFileSync } from "node:fs";
import { ROUTES } from "../src/data/routes.js";

const paths = {};

for (const route of ROUTES) {
  // Every route is a loop, so the bus returns to the first stop
  const points = [...route.stops, route.stops[0]];
  const coordinates = points.map((s) => `${s.longitude},${s.latitude}`).join(";");
  const url = `https://router.project-osrm.org/route/v1/driving/${coordinates}?overview=full&geometries=geojson`;

  const response = await fetch(url);
  const data = await response.json();

  if (data.code !== "Ok") {
    console.error(`Routing failed for ${route.id}`, data);
    process.exit(1);
  }

  // OSRM returns [longitude, latitude] but Leaflet needs [latitude, longitude]
  paths[route.id] = data.routes[0].geometry.coordinates.map(([lng, lat]) => [lat, lng]);
  console.log(`${route.id} saved ${paths[route.id].length} points`);
}

const content =
  "// Generated by scripts/generateRoute.mjs, do not edit by hand\n" +
  "export const ROUTE_PATHS = " +
  JSON.stringify(paths) +
  ";\n";

writeFileSync("src/data/routePaths.js", content);
console.log("Saved src/data/routePaths.js");